"""Evaluate a synthetic QA dataset with the hallucination metric.

Loads a synthetic QA dataset generated by ``dataset_generator.py`` and checks
that each ``expected_output`` is faithful to its associated ``context``
(validation of the records, not a RAG pipeline test). Results are saved to
``evals/``.
"""

import argparse
import json
import logging
import sys
from pathlib import Path

from deepeval.metrics import HallucinationMetric
from deepeval.test_case import LLMTestCase

from config import get_llm_provider_name, get_provider
from paths import DATASETS_DIR, EVALS_DIR
from providers import CustomOpenAI

LOGGER = logging.getLogger(__name__)


def latest_dataset(datasets_dir: Path) -> Path:
    """Return the most recent ``synthetic_qa_*.json`` file in the directory.

    Parameters
    ----------
    datasets_dir:
        Directory in which to look for dataset files.

    Returns
    -------
    Path
        Path of the most recent dataset file (by name order).

    Raises
    ------
    FileNotFoundError
        If no ``synthetic_qa_*.json`` file is found.
    """
    candidates = sorted(datasets_dir.glob("synthetic_qa_*.json"))
    if not candidates:
        raise FileNotFoundError(
            f"No synthetic_qa_*.json dataset found in {datasets_dir}"
        )
    return candidates[-1]


def load_data(dataset_path: Path) -> list[dict]:
    """Load a JSON dataset and check that it is a list.

    Parameters
    ----------
    dataset_path:
        Path of the JSON dataset file.

    Returns
    -------
    list[dict]
        The dataset records.

    Raises
    ------
    FileNotFoundError
        If ``dataset_path`` does not exist.
    TypeError
        If the file content is not a JSON list.
    """
    if not dataset_path.is_file():
        raise FileNotFoundError(f"Dataset not found: {dataset_path}")
    with open(dataset_path, "r", encoding="utf-8") as f_in:
        data = json.load(f_in)
    if not isinstance(data, list):
        raise TypeError(f"Invalid format for {dataset_path}: a list was expected")
    return data


def build_test_case(record: dict) -> LLMTestCase:
    """Build an LLMTestCase from a dataset record.

    ``actual_output`` takes the value of ``expected_output`` to validate that
    the generated record is faithful to its context (no hallucination).

    Parameters
    ----------
    record:
        A single dataset record.

    Returns
    -------
    LLMTestCase
        The test case to feed to the hallucination metric.
    """
    return LLMTestCase(
        input=record.get("input", ""),
        actual_output=record.get("expected_output", ""),
        context=record.get("context") or [],
    )


def evaluate_dataset(
    dataset_name: str, llm_provider: str, threshold: float
) -> list[dict]:
    """Measure the hallucination of each record and return the results.

    Parameters
    ----------
    dataset_name:
        File name of the dataset inside ``DATASETS_DIR``.
    llm_provider:
        Name of the LLM provider used as the evaluation model.
    threshold:
        Hallucination score threshold of the metric.

    Returns
    -------
    list[dict]
        Evaluation results, one dict per record.
    """
    eval_llm = CustomOpenAI.from_provider(get_provider(llm_provider))
    halu_metric = HallucinationMetric(threshold=threshold, model=eval_llm)

    data = load_data(DATASETS_DIR / dataset_name)
    results: list[dict] = []
    failures = 0

    for index, record in enumerate(data, start=1):
        test_case = build_test_case(record)
        try:
            halu_metric.measure(test_case)
        except Exception as exc:  # noqa: BLE001 - tolerate per-item failures
            failures += 1
            LOGGER.error(
                "Failed to evaluate item %d/%d: %s",
                index,
                len(data),
                exc,
            )
            continue

        results.append(
            {
                "hallucination_metric": {
                    "score": halu_metric.score,
                    "reason": halu_metric.reason,
                }
            }
        )
        LOGGER.info(
            "Evaluated item %d/%d (score: %.2f)",
            index,
            len(data),
            halu_metric.score,
        )

    if failures:
        LOGGER.warning("%d item(s) failed out of %d", failures, len(data))
    return results


def save_results(results: list[dict], dataset_name: str, output_dir: Path) -> Path:
    """Save the evaluation results and return the file path.

    Parameters
    ----------
    results:
        Evaluation results to write.
    dataset_name:
        Name of the evaluated dataset, used in the output file name.
    output_dir:
        Directory in which the results file is created.

    Returns
    -------
    Path
        Path of the written results file.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / f"eval_data_{dataset_name}.json"
    with open(output_path, "w", encoding="utf-8") as f_out:
        json.dump(results, f_out, ensure_ascii=False, indent=2)
    LOGGER.info("Results saved to %s", output_path)
    return output_path


def main() -> None:
    """Evaluate the hallucination of a synthetic dataset via the CLI."""
    parser = argparse.ArgumentParser(
        description="Evaluate the hallucination of a synthetic dataset's records."
    )
    parser.add_argument(
        "--dataset",
        default=None,
        help="Dataset file name (default: the most recent one in datasets/).",
    )
    parser.add_argument(
        "--llm-provider",
        default=get_llm_provider_name(),
        help="LLM provider name in config.yaml (default: %(default)s).",
    )
    parser.add_argument(
        "--threshold",
        type=float,
        default=0.8,
        help="Hallucination metric threshold (default: 0.8).",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=EVALS_DIR,
        help="Output directory for the evaluations (default: ./evals).",
    )
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")

    dataset_name = args.dataset or latest_dataset(DATASETS_DIR).name
    LOGGER.info("Evaluating dataset %s...", dataset_name)

    try:
        results = evaluate_dataset(
            dataset_name=dataset_name,
            llm_provider=args.llm_provider,
            threshold=args.threshold,
        )
    except Exception as exc:  # noqa: BLE001 - catch-all for CLI entry point
        LOGGER.error("Evaluation failed: %s", exc)
        sys.exit(1)

    save_results(results, dataset_name, args.output_dir)


if __name__ == "__main__":
    main()
