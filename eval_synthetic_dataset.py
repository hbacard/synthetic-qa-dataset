"""Evaluate a synthetic dataset with the hallucination metric.

Loads a goldens dataset generated by ``dataset_generator.py`` and checks that
each ``expected_output`` is faithful to its associated ``context`` (validation
of the goldens, not a RAG pipeline test). Results are saved to ``evals/``.
"""

import argparse
import json
import logging
import sys
from pathlib import Path

from deepeval.metrics import HallucinationMetric
from deepeval.test_case import LLMTestCase

from config import get_provider
from paths import DATASETS_DIR, EVALS_DIR
from providers import CustomOpenAI

LOGGER = logging.getLogger(__name__)


def latest_dataset(datasets_dir: Path) -> Path:
    """Return the most recent ``goldens_*.json`` file in the directory."""
    candidates = sorted(datasets_dir.glob("goldens_*.json"))
    if not candidates:
        raise FileNotFoundError(
            f"No goldens_*.json dataset found in {datasets_dir}"
        )
    return candidates[-1]


def load_data(dataset_path: Path) -> list[dict]:
    """Load a JSON dataset and check that it is a list."""
    if not dataset_path.is_file():
        raise FileNotFoundError(f"Dataset not found: {dataset_path}")
    with open(dataset_path, "r", encoding="utf-8") as f_in:
        data = json.load(f_in)
    if not isinstance(data, list):
        raise ValueError(
            f"Invalid format for {dataset_path}: a list was expected"
        )
    return data


def build_test_case(record: dict) -> LLMTestCase:
    """Build an LLMTestCase from a dataset record.

    ``actual_output`` takes the value of ``expected_output`` to validate that
    the generated golden is faithful to its context (no hallucination).
    """
    return LLMTestCase(
        input=record.get("input", ""),
        actual_output=record.get("expected_output", ""),
        context=record.get("context") or [],
    )


def evaluate_dataset(
    dataset_name: str, provider: str, threshold: float
) -> list[dict]:
    """Measure the hallucination of each golden and return the results."""
    eval_llm = CustomOpenAI.from_provider(get_provider(provider))
    halu_metric = HallucinationMetric(threshold=threshold, model=eval_llm)

    data = load_data(DATASETS_DIR / dataset_name)
    results: list[dict] = []
    failures = 0

    for index, record in enumerate(data, start=1):
        test_case = build_test_case(record)
        try:
            halu_metric.measure(test_case)
        except Exception as exc:
            failures += 1
            LOGGER.error(
                "Failed to evaluate item %d/%d: %s",
                index,
                len(data),
                exc,
            )
            continue

        results.append(
            {
                "hallucination_metric": {
                    "score": halu_metric.score,
                    "reason": halu_metric.reason,
                }
            }
        )
        LOGGER.info(
            "Evaluated item %d/%d (score: %.2f)",
            index,
            len(data),
            halu_metric.score,
        )

    if failures:
        LOGGER.warning("%d item(s) failed out of %d", failures, len(data))
    return results


def save_results(results: list[dict], dataset_name: str, output_dir: Path) -> Path:
    """Save the evaluation results and return the file path."""
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / f"eval_data_{dataset_name}.json"
    with open(output_path, "w", encoding="utf-8") as f_out:
        json.dump(results, f_out, ensure_ascii=False, indent=2)
    LOGGER.info("Results saved to %s", output_path)
    return output_path


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Evaluate the hallucination of a dataset's goldens."
    )
    parser.add_argument(
        "--dataset",
        default=None,
        help="Dataset file name (default: the most recent one in datasets/).",
    )
    parser.add_argument(
        "--provider",
        default="albert",
        help="Provider name in config.yaml (default: albert).",
    )
    parser.add_argument(
        "--threshold",
        type=float,
        default=0.8,
        help="Hallucination metric threshold (default: 0.8).",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=EVALS_DIR,
        help="Output directory for the evaluations (default: ./evals).",
    )
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")

    dataset_name = args.dataset or latest_dataset(DATASETS_DIR).name
    LOGGER.info("Evaluating dataset %s...", dataset_name)

    try:
        results = evaluate_dataset(
            dataset_name=dataset_name,
            provider=args.provider,
            threshold=args.threshold,
        )
    except Exception as exc:
        LOGGER.error("Evaluation failed: %s", exc)
        sys.exit(1)

    save_results(results, dataset_name, args.output_dir)


if __name__ == "__main__":
    main()
